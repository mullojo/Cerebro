// Build-time template compiler only. Vue + Tailwind load from pinned CDNs.
// Full compiler is a pinned build-only dependency; browser builds omit module mode.
import { compile } from '@vue/compiler-dom';
import * as fs from 'node:fs/promises';

await fs.mkdir('web/generated', { recursive: true });
const uiClasses = new Set();
for (const file of await fs.readdir('web/views', { withFileTypes: true })) {
  if (!file.name.endsWith('.html')) continue;
  const source = await fs.readFile(`web/views/${file.name}`, 'utf8');
  for (const match of source.matchAll(/\sclass="([^"]+)"/g)) {
    for (const token of match[1].split(/\s+/)) if (token) uiClasses.add(token);
  }
  const { code } = compile(source, { mode: 'module', prefixIdentifiers: true,
    hoistStatic: true, runtimeModuleName: 'https://esm.sh/vue@3.5.45' });
  await fs.writeFile(`web/generated/${file.name.replace('.html', '.js')}`,
    '// Generated by npm run build. Edit web/views/ instead.\n' + code + '\n');
}
const theme = await fs.readFile('web/theme.css', 'utf8');
const shell = await fs.readFile('web/shell.html', 'utf8');
await fs.writeFile('web/index.html', shell.replace('/* THEME */', theme).replace('/* UI_CLASSES */', [...uiClasses].join(' ')));
for (const directory of await fs.readdir('projects', { withFileTypes: true })) {
  if (!directory.isDirectory() || !/^[a-z0-9-]+$/.test(directory.name)) continue;
  const base = `projects/${directory.name}`;
  // Plain HTML projects remain valid; only compile projects using this convention.
  for (const [source, target, template] of [['view.html', 'view.js', true], ['shell.html', 'index.html', false]]) {
    let content;
    try { content = await fs.readFile(`${base}/${source}`, 'utf8'); }
    catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    const output = template ? compile(content, { mode: 'module', prefixIdentifiers: true,
      hoistStatic: true, runtimeModuleName: 'https://esm.sh/vue@3.5.45' }).code : content.replace('/* THEME */', theme);
    await fs.writeFile(`${base}/${target}`, output.trimEnd() + '\n');
  }
}
console.log('Built Vue templates and HTML shell. Vue 3.5.45 / Tailwind 4.3.5 load from CDN.');
